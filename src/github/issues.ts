import type { ScoredCandidate, ScoutIssue, IssueType } from "@/shared/types";
import type { SurfaceConfig } from "@configs/surfaces";
import { getVerdict } from "@/scoring";

const ISSUE_LABELS = {
	auto_issue: ["ai-scout", "needs-human-review"],
	review_candidate: ["ai-scout", "needs-human-review"],
} as const;

/**
 * Compose a GitHub issue from a scored candidate.
 */
export function composeIssue(
	candidate: ScoredCandidate,
	surface: SurfaceConfig,
	screenshotUrl: string,
): ScoutIssue {
	const verdict = getVerdict(candidate);
	const issueType = resolveIssueType(candidate);

	return {
		title: formatTitle(issueType, surface),
		type: issueType,
		surface: surface.id,
		browser: surface.browser,
		locale: surface.locale,
		score: candidate.totalScore,
		domSnippet: candidate.block.html.slice(0, 1500),
		screenshotUrl,
		explanation: formatExplanation(candidate),
		category: candidate.category,
		blockFingerprint: candidate.blockFingerprint,
		layoutFingerprint: candidate.layoutFingerprint,
	};
}

/**
 * Format issue body for GitHub.
 */
export function formatIssueBody(issue: ScoutIssue): string {
	const signals = issue.explanation;

	return `## AI Scout Detection

| Field | Value |
|---|---|
| **Surface** | ${issue.surface} |
| **Browser** | ${issue.browser} |
| **Locale** | ${issue.locale} |
| **Type** | \`${issue.type}\` |
| **Category** | \`${issue.category}\` |
| **Score** | ${issue.score}/10 |

## Signals

${signals}

## DOM Snippet

\`\`\`html
${issue.domSnippet}
\`\`\`

## Screenshot

![Screenshot](${issue.screenshotUrl})

## Suggested Action

Review the detected element and add appropriate CSS selectors to \`src/selectors/\` if it should be hidden by Debloat.

---

<!-- scout-fingerprint: ${issue.blockFingerprint} -->
<!-- scout-layout: ${issue.layoutFingerprint} -->
<!-- scout-surface: ${issue.surface} -->
<!-- scout-profile: ${issue.surface}:${issue.browser}:${issue.locale} -->
*Generated by [Debloat AI Scout](https://github.com/investblog/debloat-ai-scout)*`;
}

/**
 * Create issue via GitHub REST API.
 */
export async function createGitHubIssue(
	issue: ScoutIssue,
	owner: string,
	repo: string,
	token: string,
): Promise<{ number: number; url: string }> {
	const body = formatIssueBody(issue);
	const verdict = issue.score >= 6 ? "auto_issue" : "review_candidate";
	const labels = [...ISSUE_LABELS[verdict]];

	const response = await fetch(`https://api.github.com/repos/${owner}/${repo}/issues`, {
		method: "POST",
		headers: {
			Authorization: `token ${token}`,
			"Content-Type": "application/json",
			Accept: "application/vnd.github+json",
		},
		body: JSON.stringify({
			title: issue.title,
			body,
			labels,
		}),
	});

	if (!response.ok) {
		const text = await response.text();
		throw new Error(`GitHub API error ${response.status}: ${text}`);
	}

	const data = (await response.json()) as { number: number; html_url: string };
	return { number: data.number, url: data.html_url };
}

function resolveIssueType(candidate: ScoredCandidate): IssueType {
	if (candidate.category === "unknown_candidate") return "unknown_candidate_requires_review";
	return "new_ai_surface";
}

function formatTitle(type: IssueType, surface: SurfaceConfig): string {
	const typeLabels: Record<IssueType, string> = {
		new_ai_surface: "New AI surface detected",
		selector_regression: "Selector regression suspected",
		unknown_candidate_requires_review: "Unknown candidate block detected",
	};
	return `[AI Scout] ${typeLabels[type]} on ${surface.name} (${surface.locale})`;
}

function formatExplanation(candidate: ScoredCandidate): string {
	if (candidate.signals.length === 0) return "No specific signals detected.";

	return candidate.signals
		.map((s) => `- **${s.type}**: \`${s.value}\` (+${s.score})`)
		.join("\n");
}
